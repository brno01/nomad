#!/usr/bin/env python3
"""Generate the Steam Input layout "Ragnarok Online - Apex 3 (stream)".

Target: Xbox 360 controller (Sunshine virtual pad, `gamepad = x360`), used by a
Steam non-Steam shortcut running Ragnarok Online under Proton.

Edit the TABLES below, then regenerate:

    uv run --no-project --with vdf python -I ragnarok-stream/steam/build_layout.py
    uv run --no-project --with vdf python -I ragnarok-stream/steam/build_layout.py --check

The output is plain text VDF written by hand (the `vdf` package is only needed
by the tests), because Steam repeats the "binding" key for multi-key combos and
dict-based writers cannot do that.

Binding mini-language used in the tables:
    "F1"            key_press F1
    "Ctrl+F1"       LEFT_CONTROL + F1 (several key_press bindings in one activator)
    "Alt+E"         LEFT_ALT + E
    "Insert"        INSERT        ("Esc", "Enter", "Tab" also work)
    "mouse:LEFT"    mouse_button LEFT
    "wheel:UP"      mouse_wheel SCROLL_UP   ("wheel:DOWN" -> SCROLL_DOWN)
    "osk"           controller_action SHOW_KEYBOARD (Steam on-screen keyboard)
    "layer:NAME"    hold the action layer NAME while pressed
    "A & B"         both bindings fire on the same press
"""

from __future__ import annotations

import sys
from pathlib import Path

OUT_PATH = Path(__file__).resolve().parent / "ragnarok-apex3.vdf"

TITLE = "Ragnarok Online - Apex 3 (stream)"
DESCRIPTION = (
    "Ragnarok Online via Sunshine/Moonlight with a Flydigi Apex 3 (Xbox 360 mode). "
    "Left stick = mouse region around the character (edge = hold left click), "
    "right stick = cursor, LT = second hotkey row, LB = windows. "
    "Generated by build_layout.py - do not edit by hand."
)

# --------------------------------------------------------------------------
# DATA TABLES - change keys here.
# --------------------------------------------------------------------------

# PROVISIONAL - confirm in the RO client's shortcut settings.
# Second hotkey row: slots 1..9 are bound on A, B, X, Y, DPAD up, right, down,
# left, RB while LT is held. Change this one constant to remap the whole row.
ROW2_MODIFIER = "Ctrl"
ROW2_KEYS = [f"{ROW2_MODIFIER}+F{n}" for n in range(1, 10)]
# Physical inputs for slots 1..9 (same order as ROW2_KEYS).
HOTKEY_SLOT_INPUTS = ["A", "B", "X", "Y", "DPAD_UP", "DPAD_RIGHT", "DPAD_DOWN", "DPAD_LEFT", "RB"]

# Layer names (also the titles shown in Steam).
LAYER_ROW2 = "Fileira 2"
LAYER_WINDOWS = "Janelas"

# BASE layer. Keys are Xbox 360 physical inputs.
BASE = {
    "A": "F1",
    "B": "F2",
    "X": "F3",
    "Y": "F4",
    "DPAD_UP": "F5",
    "DPAD_RIGHT": "F6",
    "DPAD_DOWN": "F7",
    "DPAD_LEFT": "F8",
    "RB": "F9",
    "START": "Esc",
    "BACK": "osk & Enter",  # Enter opens chat AND Steam's on-screen keyboard
    "LT": f"layer:{LAYER_ROW2}",
    "LB": f"layer:{LAYER_WINDOWS}",
    "RT": "mouse:LEFT",  # full pull; hold-able
    "R3": "mouse:RIGHT",
    "L3": "Insert",  # sit / stand
    # Left stick edge ("outer ring") = hold left mouse button -> keep walking.
    "LSTICK_EDGE": "mouse:LEFT",
}

# "Fileira 2" layer, active while LT is held. Inputs not listed fall through
# to BASE.
ROW2 = dict(zip(HOTKEY_SLOT_INPUTS, ROW2_KEYS))

# "Janelas" layer, active while LB is held. Alt shortcuts: TO CONFIRM in the
# RO client (Options > Shortcuts).
WINDOWS = {
    "A": "Alt+E",  # inventory
    "B": "Alt+S",  # skills
    "X": "Alt+Q",  # equipment
    "Y": "Alt+A",  # status
    "DPAD_UP": "Ctrl+Tab",  # minimap
    "DPAD_RIGHT": "Alt+Z",  # party
    "DPAD_DOWN": "Alt+G",  # guild
    "DPAD_LEFT": "Alt+U",  # quests
    # Right stick becomes a mouse wheel instead of the cursor.
    "RSTICK_UP": "wheel:UP",
    "RSTICK_DOWN": "wheel:DOWN",
}

# Layers in preset-id order (base is preset 0, first layer is preset 1, ...).
LAYERS = [(LAYER_ROW2, ROW2), (LAYER_WINDOWS, WINDOWS)]

# Stick tuning. Steam scales most "radius"/"threshold" settings to 0..32767.
LSTICK_EDGE_RADIUS = 26000  # ~80% of travel: beyond this = outer ring (hold LMB)
MOUSE_REGION_SIZE = 30  # percent of screen height (radius) - UNCERTAIN key name
RSTICK_SENSITIVITY = 100  # moderate; 100 = Steam default scale

# Key names Steam wants (key_press <NAME>).
KEY_ALIASES = {
    "CTRL": "LEFT_CONTROL",
    "ALT": "LEFT_ALT",
    "SHIFT": "LEFT_SHIFT",
    "ESC": "ESCAPE",
    "ENTER": "RETURN",
}

# Hold-layer command. UNCERTAIN: exact token; swap here if Steam rejects it.
HOLD_LAYER_COMMAND = "controller_action HOLD_LAYER"

# --------------------------------------------------------------------------
# Physical input -> (Steam source, input name inside the group)
# --------------------------------------------------------------------------

INPUT_MAP = {
    "A": ("button_diamond", "button_a"),
    "B": ("button_diamond", "button_b"),
    "X": ("button_diamond", "button_x"),
    "Y": ("button_diamond", "button_y"),
    "DPAD_UP": ("dpad", "dpad_north"),
    "DPAD_RIGHT": ("dpad", "dpad_east"),
    "DPAD_DOWN": ("dpad", "dpad_south"),
    "DPAD_LEFT": ("dpad", "dpad_west"),
    "LB": ("switch", "left_bumper"),
    "RB": ("switch", "right_bumper"),
    "START": ("switch", "button_menu"),  # Xbox "Menu"/Start
    "BACK": ("switch", "button_escape"),  # Xbox "View"/Back
    "LT": ("left_trigger", "click"),  # full pull
    "RT": ("right_trigger", "click"),  # full pull
    "L3": ("joystick", "click"),
    "LSTICK_EDGE": ("joystick", "edge"),
    "R3": ("right_joystick", "click"),
    "RSTICK_UP": ("right_joystick", "dpad_north"),
    "RSTICK_DOWN": ("right_joystick", "dpad_south"),
}

SOURCE_ORDER = ["button_diamond", "dpad", "switch", "left_trigger", "right_trigger", "joystick", "right_joystick"]

# --------------------------------------------------------------------------
# Binding parsing
# --------------------------------------------------------------------------


def _key(name: str) -> str:
    up = name.strip().upper()
    return KEY_ALIASES.get(up, up)


def parse_binding(spec: str, layer_ids: dict[str, int]) -> list[str]:
    """Turn a mini-language spec into the list of Steam binding strings."""
    out: list[str] = []
    for part in (p.strip() for p in spec.split("&")):
        if part == "osk":
            out.append("controller_action SHOW_KEYBOARD")
        elif part.startswith("mouse:"):
            out.append(f"mouse_button {part[6:].upper()}")
        elif part.startswith("wheel:"):
            out.append(f"mouse_wheel SCROLL_{part[6:].upper()}")
        elif part.startswith("layer:"):
            out.append(f"{HOLD_LAYER_COMMAND} {layer_ids[part[6:]]} 0 0")
        else:
            out.extend(f"key_press {_key(k)}" for k in part.split("+"))
    return out


# --------------------------------------------------------------------------
# VDF model: a block is a list of (key, value); value is str or block.
# Lists of pairs (not dicts) so duplicate keys such as "binding" survive.
# --------------------------------------------------------------------------

Block = list


def activator(bindings: list[str]) -> Block:
    return [("activators", [("Full_Press", [("bindings", [("binding", b) for b in bindings])])])]


def group_block(gid: int, mode: str, inputs: dict[str, list[str]], settings: list | None) -> Block:
    g: Block = [("id", str(gid)), ("mode", mode), ("inputs", [(n, activator(b)) for n, b in inputs.items()])]
    if settings:
        g.append(("settings", settings))
    return g


def mode_and_settings(source: str, touched: set[str]):
    """Group mode and settings for a source."""
    if source == "button_diamond":
        return "four_buttons", None
    if source == "dpad":
        return "dpad", None
    if source == "switch":
        return "switches", None
    if source in ("left_trigger", "right_trigger"):
        return "trigger", None
    if source == "joystick":
        # UNCERTAIN: no real example of a mouse_region group with these
        # settings was found. "edge_binding_radius" is a real key (dpad groups);
        # the two others are best guesses. Verify in the Steam UI: region about
        # 30% of screen height, "return cursor on deactivation" OFF.
        return "mouse_region", [
            ("edge_binding_radius", str(LSTICK_EDGE_RADIUS)),
            ("mouse_region_size", str(MOUSE_REGION_SIZE)),  # UNCERTAIN key name
            ("return_cursor_on_deactivation", "0"),  # UNCERTAIN key name
        ]
    if source == "right_joystick":
        if touched & {"RSTICK_UP", "RSTICK_DOWN"}:
            # Stick as mouse wheel: dpad mode on the stick.
            return "dpad", [("requires_click", "0")]
        # UNCERTAIN: sensitivity key names for joystick_mouse.
        return "joystick_mouse", [
            ("sensitivity_horiz_scale", str(RSTICK_SENSITIVITY)),
            ("sensitivity_vert_scale", str(RSTICK_SENSITIVITY)),
        ]
    raise ValueError(source)


def build_preset_groups(layer: dict[str, str] | None, start_id: int, layer_ids: dict[str, int]):
    """Return (groups, group_source_bindings, next_id) for one preset.

    A layer only emits groups for the sources it overrides; the others are left
    out of group_source_bindings and are inherited from base. For an overridden
    source, inputs the layer does not list are copied from BASE, because a
    Steam group replaces the whole source (it does not merge per input).
    """
    merged = dict(BASE)
    if layer:
        merged.update(layer)
    overrides = set(layer) if layer else set(BASE)
    groups: list[Block] = []
    sources: list[tuple[str, str]] = []
    gid = start_id
    for source in SOURCE_ORDER:
        names = [n for n, (s, _) in INPUT_MAP.items() if s == source]
        touched = {n for n in names if n in overrides}
        if not touched:
            continue
        inputs = {INPUT_MAP[n][1]: parse_binding(merged[n], layer_ids) for n in names if n in merged}
        mode, settings = mode_and_settings(source, touched)
        groups.append(group_block(gid, mode, inputs, settings))
        sources.append((str(gid), f"{source} active"))
        gid += 1
    return groups, sources, gid


def build() -> Block:
    layer_ids = {name: i + 1 for i, (name, _) in enumerate(LAYERS)}
    preset_names = ["Default"] + [f"Preset_{1000001 + i}" for i in range(len(LAYERS))]
    specs = [None] + [spec for _, spec in LAYERS]

    all_groups: list[Block] = []
    presets: list[Block] = []
    next_id = 0
    for pid, (pname, spec) in enumerate(zip(preset_names, specs)):
        groups, sources, next_id = build_preset_groups(spec, next_id, layer_ids)
        all_groups.extend(groups)
        presets.append([("id", str(pid)), ("name", pname), ("group_source_bindings", sources)])

    root: Block = [
        ("version", "3"),
        ("revision", "1"),
        ("title", TITLE),
        ("description", DESCRIPTION),
        ("creator", ""),
        ("controller_type", "controller_xbox360"),
        ("major_revision", "0"),
        ("minor_revision", "0"),
        ("Timestamp", "0"),
        ("actions", [("Default", [("title", "Default"), ("legacy_set", "1")])]),
        (
            "action_layers",
            [
                (
                    preset_names[i + 1],
                    [
                        ("title", layer_name),
                        ("legacy_set", "1"),
                        ("set_layer", "1"),
                        ("parent_set_name", "Default"),
                    ],
                )
                for i, (layer_name, _) in enumerate(LAYERS)
            ],
        ),
    ]
    root.extend(("group", g) for g in all_groups)
    root.extend(("preset", p) for p in presets)
    root.append(("settings", []))
    return root


# --------------------------------------------------------------------------
# Text VDF writer (Steam style: tabs, "key"<TAB><TAB>"value")
# --------------------------------------------------------------------------


def _q(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def _write(block: Block, depth: int, lines: list[str]) -> None:
    pad = "\t" * depth
    for key, value in block:
        if isinstance(value, list):
            lines.append(f"{pad}{_q(key)}")
            lines.append(f"{pad}{{")
            _write(value, depth + 1, lines)
            lines.append(f"{pad}}}")
        else:
            lines.append(f"{pad}{_q(key)}\t\t{_q(value)}")


def render() -> str:
    lines = ['"controller_mappings"', "{"]
    _write(build(), 1, lines)
    lines.append("}")
    return "\n".join(lines) + "\n"


def main(argv: list[str]) -> int:
    text = render()
    if "--check" in argv:
        current = OUT_PATH.read_text(encoding="utf-8") if OUT_PATH.exists() else None
        if current != text:
            print(f"{OUT_PATH} is out of date; run build_layout.py without --check.", file=sys.stderr)
            return 1
        print("up to date")
        return 0
    OUT_PATH.write_text(text, encoding="utf-8")
    print(f"wrote {OUT_PATH}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
